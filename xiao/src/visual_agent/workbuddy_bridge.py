"""WorkBuddy (CodeBuddy Lite) Local Gateway Bridge.

Integrates with the running WorkBuddy desktop sidecar or headless service.
The desktop client exposes a local HTTP Gateway (by default on 127.0.0.1)
protected by CODEBUDDY_GATEWAY_PASSWORD.

Includes workspace context binding (`cwd`) and deterministic file-block
materialization so code generated by WorkBuddy is written to disk when
the gateway returns fenced file blocks instead of executing sidecar tool writes.
"""

from __future__ import annotations

import json
import os
import re
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from uuid import uuid4


# Matches fenced code blocks annotated with a file path:
#   ```python path=src/foo.py
#   ```py:src/foo.py
#   ```python // FILE: src/foo.py
#   <!-- FILE: src/foo.py -->\n```python
_FENCED_FILE_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(
        r"```[a-zA-Z0-9_+-]*\s+(?:path|file|filepath)\s*[:=]\s*([^\s`\r\n]+)\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
    re.compile(
        r"```[a-zA-Z0-9_+-]+:([^\s`\r\n]+)\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
    re.compile(
        r"(?:#|//|<!--)\s*FILE\s*:\s*([^\r\n>]+?)(?:\s*-->)?\s*\r?\n```[a-zA-Z0-9_+-]*\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
    re.compile(
        r"```[a-zA-Z0-9_+-]*\r?\n(?:#|//)\s*FILE\s*:\s*([^\r\n]+)\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
    re.compile(
        r"(?:#|//|<!--)\s*([A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)+\.(?:py|ts|tsx|js|jsx|json|yaml|yml|toml|md))\s*(?:\s*-->)?\s*\r?\n```[a-zA-Z0-9_+-]*\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
    re.compile(
        r"```[a-zA-Z0-9_+-]*\r?\n(?:#|//)\s*([A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)+\.(?:py|ts|tsx|js|jsx|json|yaml|yml|toml|md))\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
    re.compile(
        r"(?:^|\n)(?:`{1,3})?([A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)+\.(?:py|ts|tsx|js|jsx|json|yaml|yml|toml|md))(?:`{1,3})?:?\r?\n```[a-zA-Z0-9_+-]*\r?\n([\s\S]*?)```",
        re.IGNORECASE,
    ),
)


@dataclass
class WorkBuddyGatewayInfo:
    port: int
    password: str
    pid: int | None = None
    account_id: str = "default"
    label: str = ""
    quota_exhausted_until: float = 0.0
    base_url: str = field(init=False)

    def __post_init__(self):
        self.base_url = f"http://127.0.0.1:{self.port}"

    @property
    def is_quota_exhausted(self) -> bool:
        return time.time() < self.quota_exhausted_until


@dataclass
class WorkBuddyRunResult:
    success: bool
    run_id: str = ""
    response: str = ""
    raw_events: list[dict[str, Any]] = field(default_factory=list)
    written_files: list[str] = field(default_factory=list)
    error: str | None = None
    elapsed_seconds: float = 0.0

    @property
    def is_quota_error(self) -> bool:
        if not self.error:
            return False
        err_lower = self.error.lower()
        quota_indicators = (
            "429",
            "quota",
            "rate limit",
            "token limit",
            "insufficient_quota",
            "额度",
            "限额",
            "超额",
            "exceeded",
        )
        return any(ind in err_lower for ind in quota_indicators)


def extract_and_apply_code_blocks(
    response_text: str,
    *,
    workspace_root: str | Path,
    allowed_files: list[str] | None = None,
) -> list[str]:
    """Parse annotated file code blocks from response text and write them safely inside workspace_root."""
    root = Path(workspace_root).expanduser().resolve()
    text = str(response_text or "")
    if not text.strip():
        return []

    extracted: list[tuple[str, str]] = []
    seen_paths: set[str] = set()
    for pattern in _FENCED_FILE_PATTERNS:
        for match in pattern.finditer(text):
            raw_path = match.group(1).strip().strip("`'\"")
            code_body = match.group(2)
            norm = raw_path.replace("\\", "/").lstrip("/")
            if not norm or ".." in norm.split("/") or norm in seen_paths:
                continue
            seen_paths.add(norm)
            extracted.append((norm, code_body))

    # Fallback: if there is exactly 1 target file in allowed_files and 1 generic code block
    if not extracted and allowed_files and len(allowed_files) == 1:
        single_target = str(allowed_files[0]).replace("\\", "/").lstrip("/")
        if single_target and ".." not in single_target.split("/"):
            generic_blocks = re.findall(r"```(?:[a-zA-Z0-9_+-]*)\r?\n([\s\S]*?)```", text)
            if len(generic_blocks) == 1 and generic_blocks[0].strip():
                extracted.append((single_target, generic_blocks[0]))

    written: list[str] = []
    allowed_set = {str(f).replace("\\", "/").lstrip("/") for f in allowed_files} if allowed_files is not None else None
    for rel_path, code_content in extracted:
        if allowed_set is not None and rel_path not in allowed_set:
            continue
        target = (root / rel_path).resolve()
        try:
            target.relative_to(root)
        except ValueError:
            # Never write outside the workspace root
            continue
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(code_content, encoding="utf-8")
            written.append(rel_path)
        except OSError:
            continue
    return written


def _read_configured_workbuddy_accounts() -> list[WorkBuddyGatewayInfo]:
    """Read configured multi-account WorkBuddy gateways from ~/.pacer/workbuddy_accounts.json or local."""
    candidates = [
        Path(os.path.expanduser("~/.pacer/workbuddy_accounts.json")),
        Path(".pacer/workbuddy_accounts.json"),
    ]
    accounts: list[WorkBuddyGatewayInfo] = []
    for p in candidates:
        if p.is_file():
            try:
                data = json.loads(p.read_text(encoding="utf-8"))
                if isinstance(data, list):
                    for item in data:
                        if isinstance(item, dict) and "port" in item and "password" in item:
                            accounts.append(
                                WorkBuddyGatewayInfo(
                                    port=int(item["port"]),
                                    password=str(item["password"]),
                                    account_id=str(item.get("account_id") or item.get("name") or f"port_{item['port']}"),
                                    label=str(item.get("label") or ""),
                                )
                            )
            except Exception:
                continue
    return accounts


def discover_all_workbuddy_gateways() -> list[WorkBuddyGatewayInfo]:
    """Discover all active and configured WorkBuddy gateway instances across processes and config files."""
    discovered: list[WorkBuddyGatewayInfo] = []
    seen_ports: set[int] = set()

    # 1. Configured accounts in ~/.pacer/workbuddy_accounts.json
    for acc in _read_configured_workbuddy_accounts():
        if acc.port not in seen_ports:
            seen_ports.add(acc.port)
            discovered.append(acc)

    # 2. psutil process inspection
    try:
        import psutil  # type: ignore

        for proc in psutil.process_iter(["pid", "name", "cmdline"]):
            try:
                cmdline = proc.info.get("cmdline") or []
                cmd_str = " ".join(cmdline).lower()
                if ("codebuddy" in cmd_str or "workbuddy" in cmd_str) and "--serve" in cmd_str:
                    env = proc.environ()
                    port = int(env.get("SERVER__PORT", 61386))
                    pwd = env.get("CODEBUDDY_GATEWAY_PASSWORD", "")
                    if pwd and port not in seen_ports:
                        seen_ports.add(port)
                        discovered.append(
                            WorkBuddyGatewayInfo(
                                port=port,
                                password=pwd,
                                pid=proc.pid,
                                account_id=f"pid_{proc.pid}",
                                label=f"Process {proc.pid} (Port {port})",
                            )
                        )
            except Exception:
                continue
    except ImportError:
        pass
    except Exception:
        pass

    # 3. Environment variables
    env_port = os.environ.get("CODEBUDDY_GATEWAY_PORT") or os.environ.get("WORKBUDDY_PORT")
    env_pwd = os.environ.get("CODEBUDDY_GATEWAY_PASSWORD") or os.environ.get("WORKBUDDY_PASSWORD")
    if env_pwd:
        port = int(env_port) if env_port and env_port.isdigit() else 61386
        if port not in seen_ports:
            seen_ports.add(port)
            discovered.append(
                WorkBuddyGatewayInfo(
                    port=port,
                    password=env_pwd,
                    account_id="env",
                    label=f"Env Port {port}",
                )
            )

    return discovered


class WorkBuddyAccountPool:
    """Manages multi-account pooling, health probing, and zero-waiting quota rotation."""

    _instance: WorkBuddyAccountPool | None = None

    def __init__(self, gateways: list[WorkBuddyGatewayInfo] | None = None):
        self._gateways: list[WorkBuddyGatewayInfo] = (
            gateways if gateways is not None else discover_all_workbuddy_gateways()
        )
        self._current_index: int = 0

    @classmethod
    def get_instance(cls) -> WorkBuddyAccountPool:
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    @classmethod
    def reset_instance(cls) -> None:
        cls._instance = None

    def refresh(self) -> None:
        self._gateways = discover_all_workbuddy_gateways()

    @property
    def gateways(self) -> list[WorkBuddyGatewayInfo]:
        return list(self._gateways)

    def get_active_gateway(self) -> WorkBuddyGatewayInfo | None:
        now = time.time()
        n = len(self._gateways)
        if n == 0:
            return None
        # Find first non-exhausted gateway starting from current index
        for i in range(n):
            idx = (self._current_index + i) % n
            gw = self._gateways[idx]
            if gw.quota_exhausted_until <= now:
                self._current_index = idx
                return gw
        # If all accounts are marked exhausted, return the one that expires earliest
        return min(self._gateways, key=lambda g: g.quota_exhausted_until)

    def mark_exhausted(self, port: int, cooldown_seconds: float = 300.0, reason: str = "") -> None:
        for gw in self._gateways:
            if gw.port == port:
                gw.quota_exhausted_until = time.time() + cooldown_seconds
                break
        self.rotate()

    def rotate(self) -> WorkBuddyGatewayInfo | None:
        if not self._gateways:
            return None
        self._current_index = (self._current_index + 1) % len(self._gateways)
        return self.get_active_gateway()


def _find_workbuddy_process_info() -> WorkBuddyGatewayInfo | None:
    """Find running WorkBuddy gateway info from the account pool."""
    return WorkBuddyAccountPool.get_instance().get_active_gateway()


def get_gateway_info() -> WorkBuddyGatewayInfo | None:
    """Get active WorkBuddy gateway info or return None if not running."""
    return WorkBuddyAccountPool.get_instance().get_active_gateway()


class WorkBuddyGatewayClient:
    """Client for the WorkBuddy local HTTP gateway."""

    def __init__(self, info: WorkBuddyGatewayInfo | None = None):
        self.info = info or get_gateway_info()

    @property
    def is_available(self) -> bool:
        return self.info is not None

    @property
    def is_ready(self) -> bool:
        """True if the gateway is available AND not currently busy running desktop streaming turns."""
        if not self.is_available:
            return False
        health = self.check_health(timeout_seconds=1.5)
        if not health.get("available"):
            return False
        status_data = health.get("status") or {}
        if isinstance(status_data, dict):
            inner = status_data.get("data") if isinstance(status_data.get("data"), dict) else status_data
            if inner.get("busy"):
                return False
        return True

    def _headers(self) -> dict[str, str]:
        headers = {
            "Content-Type": "application/json",
            "Accept": "application/json, text/event-stream",
        }
        if self.info and self.info.password:
            headers["Authorization"] = f"Bearer {self.info.password}"
        return headers

    def check_health(self, timeout_seconds: float = 3.0) -> dict[str, Any]:
        """Check gateway health status via GET /api/v1/status."""
        if not self.info:
            return {"available": False, "error": "WorkBuddy gateway not detected or desktop app not running."}

        url = f"{self.info.base_url}/api/v1/status"
        req = urllib.request.Request(url, headers=self._headers(), method="GET")
        try:
            with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return {"available": True, "status": data, "port": self.info.port}
        except Exception as exc:
            return {"available": False, "error": str(exc), "port": self.info.port}

    def list_sessions(self, timeout_seconds: float = 5.0) -> list[dict[str, Any]]:
        """List active/recent sessions via GET /api/v1/sessions."""
        if not self.info:
            return []
        url = f"{self.info.base_url}/api/v1/sessions"
        req = urllib.request.Request(url, headers=self._headers(), method="GET")
        try:
            with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return data if isinstance(data, list) else data.get("sessions", [])
        except Exception:
            return []

    def create_run(
        self,
        prompt: str,
        *,
        cwd: str | Path | None = None,
        target_files: list[str] | None = None,
        apply_changes: bool = False,
        conversation_id: str | None = None,
        sender_name: str = "pacer-agent",
        timeout_seconds: float = 120.0,
    ) -> WorkBuddyRunResult:
        """Submit a prompt run to WorkBuddy and stream/collect the result."""
        if not self.info:
            return WorkBuddyRunResult(
                success=False,
                error="WorkBuddy gateway not available. Ensure WorkBuddy desktop app is open.",
            )

        conv_id = conversation_id or f"pacer-conv-{uuid4().hex[:8]}"
        req_id = f"pacer-req-{uuid4().hex[:8]}"
        workspace_path = str(Path(cwd).expanduser().resolve()) if cwd else str(Path.cwd().resolve())

        effective_prompt = prompt
        if apply_changes:
            effective_prompt = (
                f"{prompt}\n\n"
                f"Workspace Root: {workspace_path}\n"
                "IMPORTANT: If you modify or create any files, either apply them directly in the workspace "
                "or emit the complete updated file content inside a fenced block with its relative path header:\n"
                "```python path=relative/path/to/file.py\n<full file content>\n```"
            )

        payload = {
            "version": "1.0",
            "id": req_id,
            "type": "message",
            "source": {
                "platform": "generic",
                "sender": {"id": "pacer-subagent", "name": sender_name},
                "conversation": {"id": conv_id, "type": "direct"},
            },
            "context": {
                "cwd": workspace_path,
                "workspaceRoot": workspace_path,
                "targetFiles": list(target_files or []),
            },
            "payload": {
                "text": effective_prompt,
                "cwd": workspace_path,
            },
        }

        url = f"{self.info.base_url}/api/v1/runs"
        body_bytes = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        req = urllib.request.Request(url, data=body_bytes, headers=self._headers(), method="POST")

        t0 = time.time()
        try:
            with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                run_id = (
                    (data.get("data") or {}).get("runId")
                    if isinstance(data.get("data"), dict)
                    else None
                ) or data.get("runId") or data.get("id") or req_id
        except urllib.error.HTTPError as exc:
            err_msg = exc.read().decode("utf-8", errors="ignore") if hasattr(exc, "read") else str(exc)
            return WorkBuddyRunResult(
                success=False,
                error=f"HTTP {exc.code}: {err_msg}",
                elapsed_seconds=time.time() - t0,
            )
        except Exception as exc:
            return WorkBuddyRunResult(
                success=False,
                error=f"Failed to post run to WorkBuddy gateway: {exc}",
                elapsed_seconds=time.time() - t0,
            )

        # Stream SSE events from GET /api/v1/runs/{runId}/stream
        stream_url = f"{self.info.base_url}/api/v1/runs/{run_id}/stream"
        stream_req = urllib.request.Request(stream_url, headers=self._headers(), method="GET")

        collected_text: list[str] = []
        raw_events: list[dict[str, Any]] = []

        try:
            with urllib.request.urlopen(stream_req, timeout=timeout_seconds) as stream_resp:
                current_event = ""
                for line_bytes in stream_resp:
                    line = line_bytes.decode("utf-8", errors="replace").strip()
                    if not line:
                        continue
                    if line.startswith("event:"):
                        current_event = line.split(":", 1)[1].strip()
                        if current_event == "done":
                            break
                    elif line.startswith("data:"):
                        data_str = line.split(":", 1)[1].strip()
                        try:
                            event_data = json.loads(data_str)
                            raw_events.append(event_data)
                            if isinstance(event_data, dict):
                                content_val = event_data.get("content")
                                text_piece = ""
                                if isinstance(content_val, dict):
                                    text_piece = content_val.get("markdown") or content_val.get("text") or ""
                                elif isinstance(content_val, str):
                                    text_piece = content_val
                                if not text_piece:
                                    text_piece = (
                                        event_data.get("delta")
                                        or event_data.get("text")
                                        or ""
                                    )
                                if text_piece:
                                    collected_text.append(str(text_piece))
                                if event_data.get("type") == "completed":
                                    break
                        except Exception:
                            if data_str and data_str != "[DONE]":
                                collected_text.append(data_str)

                    if time.time() - t0 > timeout_seconds:
                        break

            final_response = "".join(collected_text).strip()
            written = (
                extract_and_apply_code_blocks(
                    final_response,
                    workspace_root=workspace_path,
                    allowed_files=target_files,
                )
                if apply_changes
                else []
            )
            return WorkBuddyRunResult(
                success=True,
                run_id=run_id,
                response=final_response or f"[WorkBuddy Run Completed: {run_id}]",
                raw_events=raw_events,
                written_files=written,
                elapsed_seconds=time.time() - t0,
            )

        except urllib.error.HTTPError as exc:
            err_msg = exc.read().decode("utf-8", errors="ignore") if hasattr(exc, "read") else str(exc)
            return WorkBuddyRunResult(
                success=False,
                run_id=run_id,
                error=f"HTTP {exc.code}: {err_msg}",
                elapsed_seconds=time.time() - t0,
            )
        except Exception as exc:
            final_response = "".join(collected_text).strip()
            if final_response:
                written = (
                    extract_and_apply_code_blocks(
                        final_response,
                        workspace_root=workspace_path,
                        allowed_files=target_files,
                    )
                    if apply_changes
                    else []
                )
                return WorkBuddyRunResult(
                    success=True,
                    run_id=run_id,
                    response=final_response,
                    raw_events=raw_events,
                    written_files=written,
                    elapsed_seconds=time.time() - t0,
                )
            return WorkBuddyRunResult(
                success=False,
                run_id=run_id,
                error=f"WorkBuddy streaming error: {exc}",
                elapsed_seconds=time.time() - t0,
            )


def invoke_workbuddy(
    prompt: str,
    *,
    cwd: str | Path | None = None,
    target_files: list[str] | None = None,
    apply_changes: bool = False,
    timeout_seconds: float = 120.0,
    gateway_info: WorkBuddyGatewayInfo | None = None,
) -> WorkBuddyRunResult:
    """Convenience helper to invoke WorkBuddy with a prompt and automatic multi-account pool rotation."""
    pool = WorkBuddyAccountPool.get_instance()
    if gateway_info is not None:
        client = WorkBuddyGatewayClient(gateway_info)
        res = client.create_run(
            prompt,
            cwd=cwd,
            target_files=target_files,
            apply_changes=apply_changes,
            timeout_seconds=timeout_seconds,
        )
        if not res.success and res.is_quota_error:
            pool.mark_exhausted(gateway_info.port, reason=str(res.error))
        return res

    gateways = pool.gateways
    if not gateways:
        client = WorkBuddyGatewayClient(None)
        return client.create_run(
            prompt,
            cwd=cwd,
            target_files=target_files,
            apply_changes=apply_changes,
            timeout_seconds=timeout_seconds,
        )

    # Try through available gateways in pool if quota or busy errors occur
    last_res: WorkBuddyRunResult | None = None
    tried_ports: set[int] = set()

    for _ in range(len(gateways)):
        gw = pool.get_active_gateway()
        if not gw or gw.port in tried_ports:
            break
        tried_ports.add(gw.port)

        client = WorkBuddyGatewayClient(gw)
        res = client.create_run(
            prompt,
            cwd=cwd,
            target_files=target_files,
            apply_changes=apply_changes,
            timeout_seconds=timeout_seconds,
        )
        if res.success:
            return res

        last_res = res
        if res.is_quota_error:
            pool.mark_exhausted(gw.port, reason=str(res.error))
        else:
            pool.rotate()

    return last_res or WorkBuddyRunResult(
        success=False,
        error="All WorkBuddy gateway accounts exhausted or unavailable.",
    )